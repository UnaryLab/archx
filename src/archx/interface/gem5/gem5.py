"""
gem5 interface: runs one whole system on gem5, not one module.

The query names the system: `architecture` (an archx architecture dict with modules core,
l1i, l1d, l2, l3, mc) and `workload` (an archx workload dict whose configuration has the
guest `binary` and its `arguments`). It returns the run directory and the stats file path.

The generated gem5 stdlib SE-mode script runs O3 cores on a Ruby MESI three-level hierarchy
(private L1/L2, shared banked L3). Cache sizes come from the cacti7/mcpat query keys
(bytes = bank * depth * width / 8). The processor runs at the core frequency; the board
clock, which gem5 gives the L3, directory and Ruby network, is the l3 frequency.

A run lives in <cache dir>/<hash>/ (config.py, m5out/, gem5.stdout, gem5.stderr, done.json).
The hash covers the config text and the identity (real path, size, mtime) of the gem5
binary and of the guest binary; the guest arguments are part of the config text. A run
with done.json and m5out/stats.txt is reused without calling gem5.
"""

import fcntl
import hashlib
import json
import os
import resource
import subprocess
import time

from collections import OrderedDict

from loguru import logger

from archx.utils import get_path

key_gem5_env = "GEM5_PATH"  # gem5 source root
key_cache_env = "ARCHX_GEM5_CACHE_DIR"
key_cache_version = 1
# relative to GEM5_PATH; ALL has X86 and MESI_Three_Level
gem5_binary_path = "build/ALL/gem5.opt"
run_timeout_seconds = 7200

# O3 param <- core query key (Xeon.xml/McPAT param names)
o3_params = {
    "fetchWidth": "fetch_width",
    "decodeWidth": "decode_width",
    # McPAT: decode_width sets the rename ports and issue_width == dispatch_width
    "renameWidth": "decode_width",
    "dispatchWidth": "issue_width",
    "issueWidth": "issue_width",
    "wbWidth": "issue_width",
    "commitWidth": "commit_width",
    "numROBEntries": "ROB_size",
    "LQEntries": "load_buffer_size",
    "SQEntries": "store_buffer_size",
    "numPhysIntRegs": "phy_Regs_IRF_size",
    "numPhysFloatRegs": "phy_Regs_FRF_size",
}


def cache_bytes(query, per_bank=False):
    lines = int(query["depth"]) * (1 if per_bank else int(query["bank"]))
    return lines * int(query["width"]) // 8


def guest_binary(workload_dict):
    return get_path(workload_dict["configuration"]["binary"], check_exist=False)


def generate_config(architecture_dict, workload_dict) -> str:
    core = architecture_dict["core"]
    l1i = architecture_dict["l1i"]["query"]
    l1d = architecture_dict["l1d"]["query"]
    l2 = architecture_dict["l2"]["query"]
    l3 = architecture_dict["l3"]
    mc = architecture_dict["mc"]["gem5"]
    num_cores = 1
    for count in core["instance"]:
        num_cores *= int(count)
    core_params = "\n".join(
        f"    cpu.{param} = {int(core['query'][key])}"
        for param, key in o3_params.items()
    )
    window = int(core["query"]["instruction_window_size"])
    arguments = [str(arg) for arg in workload_dict["configuration"]["arguments"]]

    return f"""# Generated by the archx gem5 interface from an archx architecture and workload; do not edit.
from gem5.components.boards.simple_board import SimpleBoard
from gem5.components.cachehierarchies.ruby.mesi_three_level_cache_hierarchy import (
    MESIThreeLevelCacheHierarchy,
)
from gem5.components.memory import {mc["memory"]}
from gem5.components.processors.cpu_types import CPUTypes
from gem5.components.processors.simple_processor import SimpleProcessor
from gem5.isas import ISA
from gem5.resources.resource import BinaryResource
from gem5.simulate.simulator import Simulator

processor = SimpleProcessor(
    cpu_type=CPUTypes("{core["gem5"]["cpu_type"]}"),
    isa=ISA("{core["gem5"]["isa"]}"),
    num_cores={num_cores},
    clk_freq="{int(core["query"]["frequency"])}MHz",
)
for core in processor.get_cores():
    cpu = core.get_simobject()
{core_params}
    cpu.instQueues[0].numEntries = {window}

cache_hierarchy = MESIThreeLevelCacheHierarchy(
    l1i_size="{cache_bytes(l1i)}B",
    l1i_assoc={int(l1i["associativity"])},
    l1d_size="{cache_bytes(l1d)}B",
    l1d_assoc={int(l1d["associativity"])},
    l2_size="{cache_bytes(l2)}B",
    l2_assoc={int(l2["associativity"])},
    # per bank
    l3_size="{cache_bytes(l3["query"], per_bank=True)}B",
    l3_assoc={int(l3["query"]["associativity"])},
    num_l3_banks={int(l3["query"]["bank"])},
)

memory = {mc["memory"]}(size="{mc["size"]}")

board = SimpleBoard(
    clk_freq="{int(l3["query"]["frequency"])}MHz",
    processor=processor,
    memory=memory,
    cache_hierarchy=cache_hierarchy,
)
board.cache_line_size = {int(l3["gem5"]["cache_line_size"])}
board.set_se_binary_workload(
    BinaryResource(local_path="{guest_binary(workload_dict)}"),
    arguments={arguments},
)

# m5_work_begin resets the stats and m5_work_end dumps them (stdlib defaults).
Simulator(board=board).run()
"""


def gem5_binary():
    root = os.environ.get(key_gem5_env)
    if root is None:
        raise RuntimeError(f"Set <{key_gem5_env}> to the gem5 source root.")
    return os.path.join(root, gem5_binary_path)


def cache_dir():
    path = os.environ.get(key_cache_env)
    if path is None:
        cache_home = os.environ.get("XDG_CACHE_HOME", os.path.expanduser("~/.cache"))
        path = os.path.join(cache_home, "archx", "gem5")
        logger.info(f"<{key_cache_env}> not set; use <{path}>.")
    return path


def file_identity(path):
    stat = os.stat(path)
    return [os.path.realpath(path), stat.st_size, stat.st_mtime_ns]


def run_gem5(config_text: str, guest_binary: str) -> str:
    """Run gem5 on config_text unless a completed run exists; return the run directory."""
    binary = gem5_binary()
    payload = [
        key_cache_version,
        config_text,
        file_identity(binary),
        file_identity(guest_binary),
    ]
    run_hash = hashlib.sha256(json.dumps(payload).encode()).hexdigest()
    run_dir = os.path.join(cache_dir(), run_hash)
    outdir = os.path.join(run_dir, "m5out")
    done_file = os.path.join(run_dir, "done.json")
    stats_file = os.path.join(outdir, "stats.txt")
    os.makedirs(run_dir, exist_ok=True)

    # flock is released when the process exits, so a crashed run leaves no stale lock
    with open(os.path.join(run_dir, "lock"), "w") as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        if os.path.isfile(done_file) and os.path.isfile(stats_file):
            logger.success(f"gem5 cache hit <{run_dir}>.")
            return run_dir

        config_file = os.path.join(run_dir, "config.py")
        with open(config_file, "w") as f:
            f.write(config_text)
        command = [binary, f"--outdir={outdir}", config_file]
        logger.info(f"Run gem5 in <{run_dir}>: {command}")
        start = time.monotonic()
        with (
            open(os.path.join(run_dir, "gem5.stdout"), "w") as out,
            open(os.path.join(run_dir, "gem5.stderr"), "w") as err,
        ):
            result = subprocess.run(
                command,
                cwd=run_dir,
                stdout=out,
                stderr=err,
                timeout=run_timeout_seconds,
            )
        wall_seconds = time.monotonic() - start
        if result.returncode != 0 or not os.path.isfile(stats_file):
            raise RuntimeError(
                f"gem5 failed with exit code {result.returncode}; see <{run_dir}/gem5.stderr>."
            )
        # peak RSS of the largest child this process has waited for (KiB on Linux)
        max_rss_kib = resource.getrusage(resource.RUSAGE_CHILDREN).ru_maxrss
        with open(done_file, "w") as f:
            json.dump({"wall_seconds": wall_seconds, "max_rss_kib": max_rss_kib}, f)
        logger.success(
            f"gem5 done in {wall_seconds:.1f} s, peak RSS {max_rss_kib} KiB: <{run_dir}>."
        )
    return run_dir


def query(
    name: str, interface: str, query: OrderedDict, input_dir=None, output_dir=None
):
    config_text = generate_config(query["architecture"], query["workload"])
    run_dir = run_gem5(config_text, guest_binary(query["workload"]))
    return OrderedDict(
        run_dir=run_dir, stats_file=os.path.join(run_dir, "m5out", "stats.txt")
    )
